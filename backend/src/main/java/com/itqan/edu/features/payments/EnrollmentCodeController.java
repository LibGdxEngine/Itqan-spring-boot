package com.itqan.edu.features.payments;

import com.itqan.edu.common.security.CurrentUserService;
import com.itqan.edu.features.enrollments.dto.EnrollmentResponse;
import com.itqan.edu.features.enrollments.mapper.EnrollmentMapper;
import com.itqan.edu.features.payments.dto.EnrollmentCodeResponse;
import com.itqan.edu.features.payments.dto.GenerateEnrollmentCodesRequest;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.data.web.PageableDefault;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.security.core.Authentication;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.Map;

@RestController
@RequiredArgsConstructor
@Tag(name = "Enrollment Codes", description = "Prepaid access codes: generated by admins, redeemed by students")
@SecurityRequirement(name = "Bearer Authentication")
public class EnrollmentCodeController {

    private final EnrollmentCodeService enrollmentCodeService;
    private final EnrollmentCodeRepository enrollmentCodeRepository;
    private final EnrollmentMapper enrollmentMapper;
    private final CurrentUserService currentUserService;

    @GetMapping("/api/admin/enrollment-codes")
    @PreAuthorize("hasRole('ADMIN')")
    @Transactional(readOnly = true)
    @Operation(summary = "List enrollment codes, optionally for one course")
    public ResponseEntity<Page<EnrollmentCodeResponse>> list(
            @RequestParam(required = false) Long courseId,
            @PageableDefault(size = 50, sort = "createdAt", direction = Sort.Direction.DESC) Pageable pageable) {
        Page<EnrollmentCode> page = courseId == null
                ? enrollmentCodeRepository.findAll(pageable)
                : enrollmentCodeRepository.findByCourseId(courseId, pageable);
        return ResponseEntity.ok(page.map(EnrollmentCodeResponse::from));
    }

    @PostMapping("/api/admin/enrollment-codes")
    @PreAuthorize("hasRole('ADMIN')")
    @Operation(summary = "Generate a batch of enrollment codes")
    public ResponseEntity<List<EnrollmentCodeResponse>> generate(
            @Valid @RequestBody GenerateEnrollmentCodesRequest request,
            Authentication authentication) {
        Long adminId = currentUserService.getCurrentUser(authentication).getId();
        List<EnrollmentCodeResponse> codes = enrollmentCodeService.generateCodes(
                        request.getCourseId(), adminId, request.getQuantity(),
                        request.getUsageLimit(), request.getExpiresAt())
                .stream().map(EnrollmentCodeResponse::from).toList();
        return ResponseEntity.status(HttpStatus.CREATED).body(codes);
    }

    @PatchMapping("/api/admin/enrollment-codes/{id}/deactivate")
    @PreAuthorize("hasRole('ADMIN')")
    @Operation(summary = "Deactivate an enrollment code")
    public ResponseEntity<Void> deactivate(@PathVariable Long id) {
        enrollmentCodeService.deactivateCode(id);
        return ResponseEntity.noContent().build();
    }

    @PostMapping("/api/enrollment-codes/redeem")
    @PreAuthorize("hasRole('STUDENT')")
    @Operation(summary = "Redeem an enrollment code", description = "Body: {\"code\": \"XXXX-XXXX-XXXX\"}")
    public ResponseEntity<EnrollmentResponse> redeem(
            @RequestBody Map<String, String> body,
            Authentication authentication) {
        Long studentId = currentUserService.getCurrentStudentId(authentication);
        return ResponseEntity.ok(enrollmentMapper.toResponse(
                enrollmentCodeService.redeemCode(body.get("code"), studentId)));
    }
}
