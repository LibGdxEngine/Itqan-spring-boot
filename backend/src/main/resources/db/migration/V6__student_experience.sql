-- Student experience: resume watching, reviews, wishlist, certificates.

ALTER TABLE lesson_enrollments ADD COLUMN IF NOT EXISTS position_seconds INTEGER;
ALTER TABLE lesson_enrollments ADD COLUMN IF NOT EXISTS last_watched_at TIMESTAMP(6) WITHOUT TIME ZONE;
ALTER TABLE enrollments ADD COLUMN IF NOT EXISTS last_lesson_id BIGINT;

CREATE TABLE IF NOT EXISTS course_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(2000),
    hidden BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_course_reviews_course_student UNIQUE (course_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_course_reviews_course ON course_reviews (course_id, hidden);

CREATE TABLE IF NOT EXISTS wishlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_wishlist_student_course UNIQUE (student_id, course_id)
);

CREATE TABLE IF NOT EXISTS certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(32) NOT NULL UNIQUE,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    student_name VARCHAR(255) NOT NULL,
    course_title VARCHAR(255) NOT NULL,
    instructor_name VARCHAR(255),
    issued_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_certificates_student_course UNIQUE (student_id, course_id)
);
