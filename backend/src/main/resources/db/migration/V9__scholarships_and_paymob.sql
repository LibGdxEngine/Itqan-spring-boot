-- Scholarship applications (students asking for a free course) and donations to the scholarship fund.
CREATE TABLE IF NOT EXISTS scholarship_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    reason VARCHAR(3000) NOT NULL,
    circumstances VARCHAR(3000),
    phone VARCHAR(40),
    status VARCHAR(20) NOT NULL,
    funding_source VARCHAR(20),
    fund_amount DOUBLE PRECISION,
    admin_note VARCHAR(1000),
    decided_by_user_id BIGINT,
    decided_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_scholarship_applications_status ON scholarship_applications (status, created_at);
CREATE INDEX IF NOT EXISTS idx_scholarship_applications_student ON scholarship_applications (student_id);
-- Only one open request per student and course.
CREATE UNIQUE INDEX IF NOT EXISTS uk_scholarship_applications_pending
    ON scholarship_applications (student_id, course_id) WHERE status = 'PENDING';

CREATE TABLE IF NOT EXISTS donations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_name VARCHAR(200),
    donor_email VARCHAR(255),
    message VARCHAR(1000),
    amount DOUBLE PRECISION NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL,
    gateway VARCHAR(20) NOT NULL,
    method VARCHAR(40),
    gateway_reference VARCHAR(64) UNIQUE,
    gateway_transaction_id VARCHAR(255),
    reference VARCHAR(255),
    recorded_by_user_id BIGINT,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_donations_status ON donations (status, created_at);


-- Paymob online payments for course purchases: our reference sent as merchant_order_id.
ALTER TABLE payments ADD COLUMN IF NOT EXISTS gateway_reference VARCHAR(64);
CREATE UNIQUE INDEX IF NOT EXISTS uk_payments_gateway_reference ON payments (gateway_reference);
